#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
VisionPlatform app icon - vector master generator.

Writes assets/icons/app-icon.svg (dark tile) and assets/icons/app-mark.svg
(transparent mark) from the same geometry as generate-icons.ps1, so the vector
source and the raster/ico exports never drift apart.

Python 3 stdlib only, no dependencies.

    python tools/icon-design/make-svg.py
"""

import math
import os

# ------------------------------- design spec -------------------------------
U = 1000.0
TILE_R = 216.0
CX = CY = 500.0
R_OUT = 318.0
R_IN = 184.0
GAP_DEG = 0.0

BRACKET_INSET = 120.0
BRACKET_ARM = 136.0
BRACKET_W = 20.0

TILE_TOP = "#3C3C4A"
TILE_MID = "#262632"
TILE_BOTTOM = "#15151C"

BLADE_A = "#28A8DE"
BLADE_B = "#38C0F0"
SEAM = "rgba(11,16,24,0.88)"
HOLE = "#09090F"
BRACKET = "rgba(79,200,245,0.80)"


def pt(r, deg):
    a = math.radians(deg)
    return CX + r * math.cos(a), CY + r * math.sin(a)


def fmt(v):
    s = "%.2f" % v
    return s.rstrip("0").rstrip(".") if "." in s else s


def xy(r, deg):
    x, y = pt(r, deg)
    return "%s %s" % (fmt(x), fmt(y))


def rounded_rect(x, y, w, h, r):
    return (
        "M %s %s L %s %s A %s %s 0 0 1 %s %s L %s %s A %s %s 0 0 1 %s %s "
        "L %s %s A %s %s 0 0 1 %s %s L %s %s A %s %s 0 0 1 %s %s Z"
        % (
            fmt(x + r), fmt(y),
            fmt(x + w - r), fmt(y),
            fmt(r), fmt(r), fmt(x + w), fmt(y + r),
            fmt(x + w), fmt(y + h - r),
            fmt(r), fmt(r), fmt(x + w - r), fmt(y + h),
            fmt(x + r), fmt(y + h),
            fmt(r), fmt(r), fmt(x), fmt(y + h - r),
            fmt(x), fmt(y + r),
            fmt(r), fmt(r), fmt(x + r), fmt(y),
        )
    )


def blade_path(i):
    a0 = i * 60.0 + GAP_DEG * 0.5
    a1 = (i + 1) * 60.0 - GAP_DEG * 0.5
    large = 1 if (a1 - a0) > 180 else 0
    return "M %s A %s %s 0 %d 1 %s L %s L %s Z" % (
        xy(R_OUT, a0), fmt(R_OUT), fmt(R_OUT), large, xy(R_OUT, a1),
        xy(R_IN, a1), xy(R_IN, a0),
    )


def hexagon():
    return " ".join(xy(R_IN, i * 60.0) for i in range(6))


def bracket_paths():
    a = BRACKET_INSET
    b = BRACKET_INSET + BRACKET_ARM
    c = U - a
    d = U - b
    return [
        "M %s %s L %s %s L %s %s" % (fmt(a), fmt(b), fmt(a), fmt(a), fmt(b), fmt(a)),
        "M %s %s L %s %s L %s %s" % (fmt(d), fmt(a), fmt(c), fmt(a), fmt(c), fmt(b)),
        "M %s %s L %s %s L %s %s" % (fmt(c), fmt(d), fmt(c), fmt(c), fmt(d), fmt(c)),
        "M %s %s L %s %s L %s %s" % (fmt(b), fmt(c), fmt(a), fmt(c), fmt(a), fmt(d)),
    ]


def build(with_tile):
    out = []
    w = out.append

    tile_d = rounded_rect(0, 0, U, U, TILE_R)
    rim_d = rounded_rect(4, 4, U - 8, U - 8, TILE_R - 5)

    w('<?xml version="1.0" encoding="UTF-8"?>')
    w("<!-- VisionPlatform app icon, 1000x1000 master. Generated by")
    w("     tools/icon-design/make-svg.py - keep it in sync with generate-icons.ps1. -->")
    w('<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="1000" '
      'viewBox="0 0 1000 1000" role="img" aria-label="VisionPlatform">')

    w("  <defs>")
    w('    <linearGradient id="tile" x1="0" y1="0" x2="0" y2="1000" gradientUnits="userSpaceOnUse">')
    w('      <stop offset="0" stop-color="%s"/>' % TILE_TOP)
    w('      <stop offset="0.44" stop-color="%s"/>' % TILE_MID)
    w('      <stop offset="1" stop-color="%s"/>' % TILE_BOTTOM)
    w("    </linearGradient>")
    w('    <radialGradient id="glow" cx="500" cy="440" r="500" gradientUnits="userSpaceOnUse">')
    w('      <stop offset="0" stop-color="#00A0E6" stop-opacity="0.22"/>')
    w('      <stop offset="1" stop-color="#00A0E6" stop-opacity="0"/>')
    w("    </radialGradient>")
    w('    <linearGradient id="bladeLight" x1="0" y1="%s" x2="0" y2="%s" gradientUnits="userSpaceOnUse">'
      % (fmt(CY - R_OUT), fmt(CY + R_OUT)))
    w('      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.133"/>')
    w('      <stop offset="0.46" stop-color="#FFFFFF" stop-opacity="0"/>')
    w('      <stop offset="1" stop-color="#000000" stop-opacity="0.306"/>')
    w("    </linearGradient>")
    w('    <radialGradient id="holeGlow" cx="500" cy="500" r="%s" gradientUnits="userSpaceOnUse">'
      % fmt(R_IN))
    w('      <stop offset="0" stop-color="#46C8FA" stop-opacity="0"/>')
    w('      <stop offset="1" stop-color="#28AAE6" stop-opacity="0.376"/>')
    w("    </radialGradient>")
    w('    <clipPath id="tileClip"><path d="%s"/></clipPath>' % tile_d)
    w('    <clipPath id="irisClip"><circle cx="500" cy="500" r="%s"/></clipPath>' % fmt(R_OUT))
    w('    <clipPath id="holeClip"><polygon points="%s"/></clipPath>' % hexagon())
    w("  </defs>")

    if with_tile:
        w('  <g id="tile">')
        w('    <path d="%s" fill="url(#tile)"/>' % tile_d)
        w('    <rect width="1000" height="1000" fill="url(#glow)" clip-path="url(#tileClip)"/>')
        w('    <path d="%s" fill="none" stroke="#FFFFFF" stroke-opacity="0.118" stroke-width="3"/>' % rim_d)
        w('    <path d="%s" fill="none" stroke="#000000" stroke-opacity="0.275" stroke-width="2"/>' % tile_d)
        w("  </g>")

    w('  <g id="roi-brackets" fill="none" stroke="%s" stroke-width="%s" '
      'stroke-linecap="round" stroke-linejoin="round">' % (BRACKET, fmt(BRACKET_W)))
    for d in bracket_paths():
        w('    <path d="%s"/>' % d)
    w("  </g>")

    w('  <g id="iris">')
    if with_tile:
        w('    <circle cx="500" cy="500" r="%s" fill="#000000" fill-opacity="0.43"/>' % fmt(R_OUT + 5))
    for i in range(6):
        w('    <path d="%s" fill="%s" stroke="%s" stroke-width="7" stroke-linejoin="round"/>'
          % (blade_path(i), BLADE_A if i % 2 == 0 else BLADE_B, SEAM))
    w('    <g clip-path="url(#irisClip)">')
    w('      <rect x="%s" y="%s" width="%s" height="%s" fill="url(#bladeLight)"/>'
      % (fmt(CX - R_OUT), fmt(CY - R_OUT), fmt(R_OUT * 2), fmt(R_OUT * 2)))
    w("    </g>")
    w("  </g>")

    w('  <g id="bore">')
    w('    <polygon points="%s" fill="%s"/>' % (hexagon(), HOLE))
    w('    <g clip-path="url(#holeClip)">')
    w('      <rect x="%s" y="%s" width="%s" height="%s" fill="url(#holeGlow)"/>'
      % (fmt(CX - R_IN), fmt(CY - R_IN), fmt(R_IN * 2), fmt(R_IN * 2)))
    w("    </g>")
    w('    <polygon points="%s" fill="none" stroke="rgba(140,230,255,0.47)" stroke-width="4"/>' % hexagon())
    w("  </g>")

    w('  <g id="reticle" stroke="rgba(208,240,255,0.53)" stroke-width="7" stroke-linecap="round">')
    w('    <line x1="%s" y1="500" x2="%s" y2="500"/>' % (fmt(CX - 122), fmt(CX - 38)))
    w('    <line x1="%s" y1="500" x2="%s" y2="500"/>' % (fmt(CX + 38), fmt(CX + 122)))
    w('    <line x1="500" y1="%s" x2="500" y2="%s"/>' % (fmt(CY - 122), fmt(CY - 38)))
    w('    <line x1="500" y1="%s" x2="500" y2="%s"/>' % (fmt(CY + 38), fmt(CY + 122)))
    w("  </g>")
    w('  <circle cx="500" cy="500" r="15" fill="rgba(160,235,255,0.92)"/>')

    r = R_OUT - 7
    sx, sy = pt(r, 197)
    ex, ey = pt(r, 241)
    w('  <path d="M %s %s A %s %s 0 0 1 %s %s" fill="none" stroke="#FFFFFF" '
      'stroke-opacity="0.314" stroke-width="11" stroke-linecap="round"/>'
      % (fmt(sx), fmt(sy), fmt(r), fmt(r), fmt(ex), fmt(ey)))

    w("</svg>")
    return "\n".join(out) + "\n"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(os.path.dirname(here))          # tools/icon-design -> repo root
    out_dir = os.path.join(root, "assets", "icons")
    os.makedirs(out_dir, exist_ok=True)

    with open(os.path.join(out_dir, "app-icon.svg"), "w", encoding="utf-8") as f:
        f.write(build(True))
    with open(os.path.join(out_dir, "app-mark.svg"), "w", encoding="utf-8") as f:
        f.write(build(False))

    print("svg written to", out_dir)


if __name__ == "__main__":
    main()
